#!/usr/bin/env bash
# Turn a Minimal archinstall into the Hyprland desktop. Safe to re-run.
#
# Run as root, either:
#   - from the live ISO after archinstall exits:  arch-chroot /mnt bash /root/setup.sh
#   - on the installed system:                    sudo ./setup.sh
#
# The autologin user defaults to the first regular user (UID 1000);
# override with SETUP_USER=name.
set -euo pipefail

[[ $EUID -eq 0 ]] || { echo "Run as root (sudo ./setup.sh)" >&2; exit 1; }

user=${SETUP_USER:-$(getent passwd 1000 | cut -d: -f1)}
[[ -n $user ]] || { echo "No user with UID 1000; set SETUP_USER" >&2; exit 1; }

packages=(
  # Hyprland desktop (archinstall's Hyprland profile, with mako instead of dunst)
  hyprland
  uwsm
  xdg-desktop-portal-hyprland
  xdg-desktop-portal-gtk   # file chooser, which the Hyprland portal lacks
  qt5-wayland
  qt6-wayland
  polkit
  hyprpolkitagent
  ttf-jetbrains-mono-nerd
  kitty
  wofi
  dolphin
  grim
  slurp

  # Notifications
  mako
  libnotify

  # Login
  sddm

  # Base utilities (from archinstall's Desktop profile)
  openssh
  htop
  wget
  smartmontools
  xdg-utils

  # Apps
  firefox
  neovim
)

services=(
  sddm
)

pacman -Syu --needed --noconfirm "${packages[@]}"
systemctl enable "${services[@]}"

# Polkit agent as a user service for every user; UWSM starts it with the
# Hyprland session (graphical-session.target).
systemctl --global enable hyprpolkitagent.service

# SDDM autologin straight into Hyprland, launched via UWSM.
install -Dm644 /dev/stdin /etc/sddm.conf.d/autologin.conf <<EOF
[Autologin]
User=$user
Session=hyprland-uwsm.desktop
EOF

# Hyprland config: start from the packaged example, which (unlike the config
# Hyprland autogenerates on first launch) has no "autogenerated" warning
# banner. The example's launcher is hyprlauncher; point it at wofi instead.
# Only replaces a missing or still-autogenerated config, never a hand-edited one.
home=$(getent passwd "$user" | cut -d: -f6)
hypr_cfg=$home/.config/hypr/hyprland.lua
if [[ ! -f $hypr_cfg ]] || grep -q 'autogenerated = true' "$hypr_cfg"; then
  install -d -o "$user" -g "$user" "$home/.config" "$home/.config/hypr"
  sed 's/^local menu *= "hyprlauncher"/local menu        = "wofi --show drun"/' \
    /usr/share/hypr/hyprland.lua >"$hypr_cfg"
  chown "$user:$user" "$hypr_cfg"
fi

echo "setup.sh: done (autologin user: $user)"
